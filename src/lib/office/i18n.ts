export const DICTS: Record<Lang, Dict> = { rw: rw as unknown as Dict, en, fr };

export function translate(lang: Lang, key: Key): string {
  return DICTS[lang][key] ?? DICTS.rw[key];
}

export function levelKey(level: string, plural = false): Key {
  const k = "level_" + level + (plural ? "_p" : "");
  return (k in rw ? k : "level_district") as Key;
}

export function statusKey(status: string): Key {
  const k = "status_" + status;
  return (k in rw ? k : "status_vacant") as Key;
}

export function parseLang(v: unknown): Lang {
  return v === "en" || v === "fr" || v === "rw" ? v : "rw";
}
